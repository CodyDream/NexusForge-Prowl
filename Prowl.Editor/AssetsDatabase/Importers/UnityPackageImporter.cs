using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;

using CDS.ProwlFork.United;

using Prowl.Editor.Projects;
using Prowl.Runtime;
using Prowl.Runtime.Resources;
using Prowl.Vector;

namespace Prowl.Editor.Importers;

/// <summary>
/// Extracts a Unity .unitypackage into the project and converts what can be converted automatically:
/// textures/models go through Prowl's normal importers, Unity materials become Lit materials, and
/// simple ScriptableObjects become <see cref="UnityScriptableObjectAsset"/> objects. Unity's .meta
/// files are kept only as archived source data - Prowl's own metadata is always generated by the
/// backend, never copied from another tool.
///
/// Prefabs and scenes are converted into real Prowl prefab/scene assets alongside the raw YAML,
/// which is kept as source data. Assets the converter cannot express (particle systems, volumes,
/// terrain) are skipped with a warning and counted in the manifest.
/// </summary>
[ImporterFor(".unitypackage")]
public sealed class UnityPackageImporter : AssetImporter
{
    public override int Version => 1;

    // A .unitypackage is a compressed archive of foreign source files, not an Echo-serialised object.
    public override EchoSource Source => EchoSource.None;

    private sealed record RawEntry(string RelativePath, string UnityPath, string Extension, byte[] Bytes);

    private static readonly Regex UnityGuidPattern = new(@"guid:\s*([0-9a-fA-F]{32})",
        RegexOptions.Compiled | RegexOptions.CultureInvariant);

    private static readonly HashSet<string> RawImportableExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".png", ".jpg", ".jpeg", ".tga", ".bmp", ".psd", ".exr",
        ".fbx", ".obj", ".gltf", ".glb", ".blend", ".bvh",
        ".wav", ".ogg", ".mp3", ".aiff", ".aif",
    };

    public override bool Import(ImportContext ctx)
    {
        if (Project.Current is not { } project)
        {
            Debug.LogError("[UnityPackageImporter] No project is open; cannot extract a .unitypackage.");
            return false;
        }

        EditorAssetBackend? backend = EditorAssetBackend.Instance;
        if (backend is null)
        {
            Debug.LogError("[UnityPackageImporter] The editor asset backend is not available.");
            return false;
        }

        IReadOnlyList<UnityPackageEntry> entries;
        try
        {
            entries = UnityPackageReader.Read(ctx.AbsolutePath);
        }
        catch (Exception ex)
        {
            Debug.LogError($"[UnityPackageImporter] Could not read '{ctx.AbsolutePath}': {ex.Message}");
            return false;
        }

        string packageFolder = SanitizeFolderName(ctx.FileName);
        var report = new UnityImportReport
        {
            SourcePath = ctx.AbsolutePath,
            OutputFolder = packageFolder,
        };

        // Unity GUID -> the path of the asset its .meta described. The Prowl GUID is filled in after
        // the raw files have been imported, since that is when the backend mints/reads its own GUIDs.
        var unityGuidToRelative = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        var rawEntries = new List<RawEntry>();

        // Unity GUID -> Prowl GUID. Paths are the bridge: a Unity .meta gives the Unity GUID for a
        // path, and the backend gives the Prowl GUID for that same path once it has been imported.
        var prowlGuidByUnityGuid = new Dictionary<string, Guid>(StringComparer.OrdinalIgnoreCase);

        void ArchiveUnityMeta(byte[] metaBytes, string assetRelative)
        {
            WriteBytes(Path.Combine(project.AssetsPath, packageFolder, "UnityMeta", assetRelative + ".meta"), metaBytes);
            report.MetaFiles++;

            string? guid = ReadUnityGuid(metaBytes);
            if (!string.IsNullOrEmpty(guid))
                unityGuidToRelative[guid] = $"{packageFolder}/{assetRelative}";
        }

        // A package can contain anything - a bad path, a corrupt YAML document or an importer that
        // rejects one file must not cost us the manifest. Report the partial result rather than
        // throwing; the backend already logs importer exceptions, this keeps a main asset in place.
        try
        {
        // ----------------------------------------------------------------
        // 1. Write the package out. .meta files are archived under UnityMeta/ so they can never be
        //    mistaken for (or overwrite) a Prowl .meta file next to an asset.
        // ----------------------------------------------------------------
        foreach (UnityPackageEntry entry in entries)
        {
            if (!TryMakeRelativePath(entry.Path, packageFolder, out string relative, out bool isMeta))
            {
                report.Skipped++;
                Debug.LogWarning($"[UnityPackageImporter] Skipped unsafe entry path '{entry.Path}'.");
                continue;
            }

            byte[] bytes = entry.Asset ?? [];

            if (isMeta)
            {
                // The archive usually carries .meta as its own entry.
                ArchiveUnityMeta(bytes, relative.Substring(0, relative.Length - ".meta".Length));
                continue;
            }

            string destination = $"{packageFolder}/{relative}";

            // Unity packages carry folder entries as extensionless paths. Creating them as files
            // would block the real files that live inside them.
            if (string.IsNullOrEmpty(Path.GetExtension(relative)))
            {
                Directory.CreateDirectory(Path.Combine(project.AssetsPath, destination));
                continue;
            }

            WriteBytes(Path.Combine(project.AssetsPath, destination), bytes);

            // Some readers attach the .meta payload to the asset entry instead.
            if (entry.Meta is { Length: > 0 } attachedMeta)
                ArchiveUnityMeta(attachedMeta, relative);

            rawEntries.Add(new RawEntry(destination, relative, Path.GetExtension(relative).ToLowerInvariant(), bytes));
        }

        report.EntryCount = rawEntries.Count;

        // ----------------------------------------------------------------
        // 2. Import the raw files through the existing importers. This is what turns a PNG into a
        //    Texture2D and an FBX into a PrefabAsset with mesh sub-assets - no format work duplicated
        //    here. The GUID returned by ImportFile is the authoritative Prowl GUID for that path.
        // ----------------------------------------------------------------
        foreach (RawEntry raw in rawEntries)
        {
            if (!RawImportableExtensions.Contains(raw.Extension)) continue;

            Guid guid = backend.ImportFile(raw.RelativePath);
            if (guid == Guid.Empty)
            {
                report.Skipped++;
                Debug.LogWarning($"[UnityPackageImporter] '{raw.RelativePath}' was written but could not be imported.");
                continue;
            }

            report.RawImports++;
            ctx.AddDependency(guid);
        }

        foreach ((string unityGuid, string relative) in unityGuidToRelative)
        {
            Guid guid = backend.PathToGuid(relative);
            if (guid == Guid.Empty)
            {
                // Resources paths are the other way the runtime names an asset. Exported packages
                // sometimes put textures under Assets/Resources, so use that as a fallback.
                string? loadPath = ToLoadPath(relative);
                if (loadPath != null)
                    guid = AssetDatabase.FindResourceGuid(loadPath, typeof(Asset));
            }

            if (guid != Guid.Empty)
                prowlGuidByUnityGuid[unityGuid] = guid;
        }

        Texture2D? ResolveTexture(UnityRef reference)
        {
            if (reference.IsNull) return null;
            string guid = reference.Guid ?? "";
            if (string.IsNullOrWhiteSpace(guid) || IsZeroGuid(guid)) return null;
            if (!prowlGuidByUnityGuid.TryGetValue(guid, out Guid prowlGuid)) return null;

            Texture2D? texture = AssetDatabase.Load<Texture2D>(prowlGuid);
            return texture.IsValid() ? texture : null;
        }

        // ----------------------------------------------------------------
        // 3. Materials. Unity stores a material as YAML whose texture slots are fileID/guid/type
        //    references; Prowl stores a Lit Material with named properties. Map the common URP and
        //    Built-in property names onto the Lit shader's names and let CreateAsset write the Echo
        //    file that the normal MaterialImporter then reads.
        // ----------------------------------------------------------------
        foreach (RawEntry raw in rawEntries)
        {
            if (raw.Extension != ".mat" || !IsUnityYaml(raw.Bytes)) continue;

            if (!TryParseFirstDocument(raw.Bytes, 21, out UnityDocument? doc))
            {
                report.Skipped++;
                continue;
            }

            // ShaderGraph materials carry a different property set (and often no _Color at all).
            // They still land on Lit; only properties that actually exist are set, so an unknown
            // ShaderGraph property is simply ignored rather than guessed at.
            var material = new Material(Shader.LoadDefault(DefaultShader.Lit))
            {
                Name = Path.GetFileNameWithoutExtension(raw.UnityPath),
            };

            ApplyTexture(material, doc, ["_BaseMap", "_MainTex", "_BaseColorMap"],
                ["base_color_map"], ResolveTexture);
            ApplyTexture(material, doc, ["_BumpMap", "_NormalMap", "_DetailNormalMap"],
                ["geometry_normal_map"], ResolveTexture);
            ApplyTexture(material, doc, ["_OcclusionMap"],
                ["ambient_occlusion_map"], ResolveTexture);
            // URP packs metalness in B and roughness in G of one texture; Prowl names those two
            // slots separately but reads the same channels, so the same texture goes into both.
            ApplyTexture(material, doc, ["_MetallicGlossMap", "_SurfaceTex"],
                ["base_metalness_map", "specular_roughness_map"], ResolveTexture);
            if (FindTexturePath(doc, ["_MetallicGlossMap", "_SurfaceTex"]) != null)
            {
                // URP's packed map is (roughness in G, metalness in B).
                material.SetTextureChannel("specular_roughness_map", 1);
                material.SetTextureChannel("base_metalness_map", 2);
            }

            if (ReadColor(doc, ["_Color", "_BaseColor"]) is { } color)
                material.SetColor("base_color", color);

            if (ReadNamedFloat(doc, "_Metallic") is float metallic)
                material.SetFloat("base_metalness", metallic);

            // Unity calls it smoothness; Prowl stores the inverse as roughness.
            if (ReadNamedFloat(doc, "_Smoothness") is float smoothness)
                material.SetFloat("specular_roughness", 1f - smoothness);

            backend.CreateAsset(material, raw.RelativePath);
            if (material.AssetID != Guid.Empty) ctx.AddDependency(material.AssetID);
            report.Materials++;
        }

        // ----------------------------------------------------------------
        // 4. Simple ScriptableObjects. Only YAML .asset files that are not URP volume profiles are
        //    converted: binary assets have no readable fields, and a volume profile's nested
        //    components reference URP script types we do not have.
        // ----------------------------------------------------------------
        foreach (RawEntry raw in rawEntries)
        {
            if (raw.Extension != ".asset" || !IsUnityYaml(raw.Bytes)) continue;

            if (!TryParseFirstDocument(raw.Bytes, 114, out UnityDocument? doc))
            {
                report.Skipped++;
                continue;
            }

            if (IsVolumeProfile(doc))
            {
                report.Skipped++;
                continue;
            }

            var scriptable = new UnityScriptableObjectAsset
            {
                Name = Path.GetFileNameWithoutExtension(raw.UnityPath),
                ClassId = doc.ClassId,
                FileId = doc.FileId,
            };

            if (doc.Fields.TryGetValue("m_Script", out UnityYamlNode scriptNode)
                && SafeParseRef(scriptNode) is { IsNull: false } script)
            {
                scriptable.ScriptGuid = script.Guid ?? "";
                scriptable.ScriptFileId = script.FileId;
                scriptable.ScriptType = script.Type;
            }

            foreach (KeyValuePair<string, UnityYamlNode> field in doc.Fields)
            {
                if (field.Key == "m_Script") continue;

                string? scalar = ScalarText(field.Value);
                if (scalar != null)
                    scriptable.Values[field.Key] = scalar;
                else if (SafeParseRef(field.Value) is { IsNull: false } reference)
                    scriptable.References[field.Key] = $"{reference.Guid}/{reference.FileId}/{reference.Type}";
            }

            backend.CreateAsset(scriptable, raw.RelativePath);
            if (scriptable.AssetID != Guid.Empty) ctx.AddDependency(scriptable.AssetID);
            report.ScriptableObjects++;
        }

        }
        catch (Exception ex)
        {
            Debug.LogError($"[UnityPackageImporter] '{ctx.FileName}' was only partially imported: {ex.Message}");
        }

        // ----------------------------------------------------------------
        // 4b. Terrains. Unity stores layer descriptions as readable YAML and heightmaps in binary
        //     TerrainData assets. Both are converted into real Prowl TerrainData assets next to the
        //     untouched source files. Each file is handled separately so one bad asset cannot stop
        //     the rest of the import. The converted assets are later used by the hierarchy converter
        //     through UnityTerrainConverter.TerrainGuidForUnityGuid.
        // ----------------------------------------------------------------
        UnityTerrainConverter.BeginPackageImport();
        var terrainConverter = new UnityTerrainConverter(backend, prowlGuidByUnityGuid, unityGuidToRelative,
            message => Debug.LogWarning(message));

        foreach (RawEntry raw in rawEntries.Where(r => r.Extension == ".terrainlayer"))
        {
            try
            {
                TerrainLayer? layer = terrainConverter.ConvertTerrainLayer(raw.Bytes, raw.RelativePath,
                    FindUnityGuid(raw, unityGuidToRelative) ?? "");
                if (layer == null) report.Skipped++;
            }
            catch (Exception ex)
            {
                report.Skipped++;
                Debug.LogWarning($"[UnityPackageImporter] Could not convert terrain layer '{raw.RelativePath}': {ex.Message}");
            }
        }

        int convertedTerrains = 0;
        foreach (RawEntry raw in rawEntries.Where(LooksLikeBinaryTerrainData))
        {
            string outputRelative = UnityHierarchyConverter.ConvertedPath(raw.RelativePath, ".terraindata");
            try
            {
                Guid guid = terrainConverter.ConvertTerrainData(raw.Bytes, FindUnityGuid(raw, unityGuidToRelative) ?? "",
                    raw.RelativePath, outputRelative);
                if (guid != Guid.Empty)
                {
                    convertedTerrains++;
                    ctx.AddDependency(guid);
                }
                else report.Skipped++;
            }
            catch (Exception ex)
            {
                report.Skipped++;
                Debug.LogWarning($"[UnityPackageImporter] Could not convert terrain data '{raw.RelativePath}': {ex.Message}");
            }
        }

        terrainConverter.WarnTerrainColliderUnsupported();

        // The main UnityImportReport is owned by another file; keep the terrain counts in a small
        // manifest asset of their own so the conversion is visible in the asset database.
        UnityTerrainImportReport terrainReport = terrainConverter.BuildReport();
        try
        {
            backend.CreateAsset(terrainReport, $"{packageFolder}/Terrain Conversion Report.asset");
            if (terrainReport.AssetID != Guid.Empty) ctx.AddDependency(terrainReport.AssetID);
        }
        catch (Exception ex)
        {
            Debug.LogWarning($"[UnityPackageImporter] Could not write the terrain conversion report: {ex.Message}");
        }

        if (convertedTerrains > 0)
            Debug.Log($"[UnityPackageImporter] Converted {convertedTerrains} terrain data asset(s) and " +
                      $"{terrainReport.ConvertedTerrainLayers} terrain layer(s) from '{ctx.FileName}'.");

        // ----------------------------------------------------------------
        // 5. Prefabs and scenes. The converter builds real GameObjects from the Unity documents,
        //    writes them as Prowl prefab/scene assets next to the raw YAML, and leaves the source
        //    files untouched. A Unity fileID is local to its YAML file; external references use the
        //    .meta GUID, which step 2 already mapped to a Prowl asset.
        // ----------------------------------------------------------------
        var prefabSources = new Dictionary<string, byte[]>(StringComparer.OrdinalIgnoreCase);
        foreach (RawEntry raw in rawEntries)
        {
            if (raw.Extension != ".prefab") continue;
            foreach ((string unityGuid, string relative) in unityGuidToRelative)
                if (string.Equals(relative, raw.RelativePath, StringComparison.OrdinalIgnoreCase))
                    prefabSources.TryAdd(unityGuid, raw.Bytes);
        }

        var converter = new UnityHierarchyConverter(backend, prowlGuidByUnityGuid, unityGuidToRelative,
            message => Debug.LogWarning(message));
        converter.SetPrefabSources(prefabSources);

        int convertedPrefabs = 0;
        foreach (RawEntry raw in rawEntries.Where(r => r.Extension == ".prefab"))
        {
            string? unityGuid = null;
            foreach ((string guid, string relative) in unityGuidToRelative)
                if (string.Equals(relative, raw.RelativePath, StringComparison.OrdinalIgnoreCase))
                {
                    unityGuid = guid;
                    break;
                }

            string outputRelative = UnityHierarchyConverter.ConvertedPath(raw.RelativePath, ".prefab");
            try
            {
                UnityHierarchyConverter.ConversionResult? result =
                    converter.ConvertPrefab(raw.Bytes, unityGuid ?? "", raw.RelativePath, outputRelative);
                if (result != null && result.AssetGuid != Guid.Empty)
                {
                    convertedPrefabs++;
                    ctx.AddDependency(result.AssetGuid);
                }
                else report.SkippedPrefabs++;
            }
            catch (Exception ex)
            {
                report.SkippedPrefabs++;
                Debug.LogWarning($"[UnityPackageImporter] Could not convert prefab '{raw.RelativePath}': {ex.Message}");
            }
        }

        int convertedScenes = 0;
        foreach (RawEntry raw in rawEntries.Where(r => r.Extension == ".unity"))
        {
            string outputRelative = UnityHierarchyConverter.ConvertedPath(raw.RelativePath, ".scene");
            try
            {
                UnityHierarchyConverter.ConversionResult? result = converter.ConvertScene(raw.Bytes, raw.RelativePath, outputRelative);
                if (result != null && result.AssetGuid != Guid.Empty)
                {
                    convertedScenes++;
                    ctx.AddDependency(result.AssetGuid);
                }
                else report.SkippedScenes++;
            }
            catch (Exception ex)
            {
                report.SkippedScenes++;
                Debug.LogWarning($"[UnityPackageImporter] Could not convert scene '{raw.RelativePath}': {ex.Message}");
            }
        }

        if (convertedPrefabs > 0 || convertedScenes > 0)
            Debug.Log($"[UnityPackageImporter] Converted {convertedPrefabs} prefab(s) and {convertedScenes} scene(s) from '{ctx.FileName}'.");

        ctx.SetMainAsset(report);
        return true;
    }

    // ================================================================
    //  Paths
    // ================================================================

    private static string SanitizeFolderName(string name)
    {
        name = name.Replace('/', '_').Replace('\\', '_').Replace(':', '_');
        foreach (char invalid in Path.GetInvalidFileNameChars())
            name = name.Replace(invalid, '_');
        name = name.Trim(' ', '.');
        return string.IsNullOrWhiteSpace(name) ? "UnityPackage" : name;
    }

    /// <summary>
    /// Turn a path from inside the archive into a safe path below the package folder. Unity packages
    /// normally start at "Assets/", and this particular source keeps its contents under a leading
    /// "Cody Dreams/" folder which only adds a redundant level once the package has its own folder.
    /// </summary>
    private static bool TryMakeRelativePath(string archivePath, string packageFolder, out string relative, out bool isMeta)
    {
        relative = "";
        isMeta = false;

        if (string.IsNullOrWhiteSpace(archivePath)) return false;

        string path = archivePath.Replace('\\', '/').TrimStart('/');
        if (path.StartsWith("Assets/", StringComparison.OrdinalIgnoreCase))
            path = path.Substring("Assets/".Length);
        if (path.StartsWith("Cody Dreams/", StringComparison.OrdinalIgnoreCase))
            path = path.Substring("Cody Dreams/".Length);
        if (!string.IsNullOrEmpty(packageFolder) &&
            path.StartsWith(packageFolder + "/", StringComparison.OrdinalIgnoreCase))
            path = path.Substring(packageFolder.Length + 1);
        // The archive also contains the package root folder itself; its contents already live
        // directly under the package folder, so that entry would only create an empty duplicate.
        if (string.Equals(path, packageFolder, StringComparison.OrdinalIgnoreCase)) return false;

        while (path.StartsWith("./", StringComparison.Ordinal))
            path = path.Substring(2);

        string[] parts = path.Split('/', StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length == 0) return false;

        foreach (string part in parts)
        {
            if (part is "." or "..") return false;
            if (part.Contains(':', StringComparison.Ordinal)) return false;
            if (Path.GetInvalidFileNameChars().Any(c => part.Contains(c))) return false;
        }

        isMeta = path.EndsWith(".meta", StringComparison.OrdinalIgnoreCase);
        relative = string.Join('/', parts);
        return true;
    }

    private static string? ToLoadPath(string relativePath)
    {
        string path = relativePath.Replace('\\', '/');
        string ext = Path.GetExtension(path);
        if (ext.Length > 0) path = path.Substring(0, path.Length - ext.Length);

        const string resources = "Resources/";
        int index = path.LastIndexOf(resources, StringComparison.OrdinalIgnoreCase);
        if (index >= 0) return path.Substring(index + resources.Length);
        return path.StartsWith(resources, StringComparison.OrdinalIgnoreCase)
            ? path.Substring(resources.Length)
            : null;
    }

    private static void WriteBytes(string absolutePath, byte[] bytes)
    {
        string? directory = Path.GetDirectoryName(absolutePath);
        if (!string.IsNullOrEmpty(directory)) Directory.CreateDirectory(directory);
        File.WriteAllBytes(absolutePath, bytes);
    }

    // ================================================================
    //  Unity YAML helpers
    // ================================================================

    private static string Decode(byte[] bytes)
        => Encoding.UTF8.GetString(bytes).TrimStart('\uFEFF');

    private static bool IsUnityYaml(byte[] bytes)
    {
        if (bytes.Length == 0) return false;
        int length = Math.Min(bytes.Length, 4096);
        string head = Encoding.UTF8.GetString(bytes, 0, length).TrimStart('\uFEFF');
        return head.Contains("%YAML", StringComparison.Ordinal) || head.Contains("!u!", StringComparison.Ordinal);
    }

    /// <summary>
    /// Binary Unity TerrainData assets are .asset files with a serialized type tree mentioning
    /// m_Heightmap, rather than readable YAML. Their path is a second, cheaper hint.
    /// </summary>
    private static bool LooksLikeBinaryTerrainData(RawEntry raw)
    {
        if (raw.Extension != ".asset" || IsUnityYaml(raw.Bytes)) return false;
        if (raw.UnityPath.Contains("Terrain", StringComparison.OrdinalIgnoreCase)) return true;

        int length = Math.Min(raw.Bytes.Length, 65536);
        string head = Encoding.ASCII.GetString(raw.Bytes, 0, length);
        return head.Contains("m_Heightmap", StringComparison.Ordinal);
    }

    private static string? ReadUnityGuid(byte[] bytes)
    {
        Match match = UnityGuidPattern.Match(Decode(bytes));
        return match.Success ? match.Groups[1].Value.ToLowerInvariant() : null;
    }

    private static bool IsZeroGuid(string guid)
        => guid.Length == 32 && guid.All(c => c == '0');

    private static string? FindUnityGuid(RawEntry raw, IReadOnlyDictionary<string, string> unityGuidToRelative)
    {
        foreach ((string unityGuid, string relative) in unityGuidToRelative)
            if (string.Equals(relative, raw.RelativePath, StringComparison.OrdinalIgnoreCase))
                return unityGuid;
        return null;
    }

    private static bool TryParseFirstDocument(byte[] bytes, long preferredClassId, out UnityDocument? document)
    {
        document = null;
        try
        {
            IReadOnlyList<UnityDocument> docs = UnityYaml.Parse(Decode(bytes));
            document = docs.FirstOrDefault(d => d.ClassId == preferredClassId) ?? docs.FirstOrDefault();
            return document != null;
        }
        catch (Exception ex)
        {
            Debug.LogWarning($"[UnityPackageImporter] Could not parse Unity YAML: {ex.Message}");
            return false;
        }
    }

    private static UnityYamlNode? Get(UnityDocument document, params string[] path)
    {
        try { return document.Get(path); }
        catch { return null; }
    }

    /// <summary>
    /// The node API exposes the structure, but only the scalar text is needed for the handful of
    /// values translated here. Read it through reflection so this importer depends on the documented
    /// UnityYamlNode surface rather than on an unspecified property name on ScalarNode.
    /// </summary>
    private static string? ScalarText(UnityYamlNode? node)
    {
        if (node is null) return null;

        Type type = node.GetType();
        const BindingFlags flags = BindingFlags.Public | BindingFlags.Instance | BindingFlags.FlattenHierarchy;

        foreach (string name in new[] { "Value", "Scalar", "Text", "Raw", "StringValue" })
        {
            PropertyInfo? property = type.GetProperty(name, flags);
            if (property != null && property.GetIndexParameters().Length == 0)
            {
                object? value = property.GetValue(node);
                if (TryToString(value, out string? text)) return text;
            }

            FieldInfo? field = type.GetField(name, flags);
            if (field != null && TryToString(field.GetValue(node), out string? fieldText)) return fieldText;
        }

        string fallback = node.ToString() ?? "";
        return fallback == type.FullName || fallback == type.Name ? null : fallback;
    }

    private static bool TryToString(object? value, out string? text)
    {
        text = value switch
        {
            string s => s,
            null => null,
            IFormattable formattable => formattable.ToString(null, CultureInfo.InvariantCulture),
            _ => value.ToString(),
        };
        return text != null;
    }

    private static float? ParseFloat(string? text)
        => float.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out float value)
            ? value
            : null;

    private static float? ReadFloat(UnityDocument document, params string[] path)
        => ParseFloat(ScalarText(Get(document, path)));

    /// <summary>
    /// Unity keeps material scalars under m_SavedProperties/m_Floats and m_Colors in modern assets,
    /// but older and ShaderGraph materials put them at the top level. Try both before giving up.
    /// </summary>
    private static string? ScalarAt(UnityDocument document, string name, params string[] tail)
    {
        string[][] locations =
        [
            ["m_SavedProperties", "m_Floats", name],
            ["m_SavedProperties", "m_Colors", name],
            [name],
        ];

        foreach (string[] location in locations)
            if (ScalarText(Get(document, [.. location, .. tail])) is { } text)
                return text;

        return null;
    }

    private static float? ReadNamedFloat(UnityDocument document, string name)
        => ParseFloat(ScalarAt(document, name));

    private static Color? ReadColor(UnityDocument document, string[] names)
    {
        foreach (string name in names)
        {
            if (ScalarAt(document, name, "r") == null) continue;

            float r = ParseFloat(ScalarAt(document, name, "r")) ?? 0f;
            float g = ParseFloat(ScalarAt(document, name, "g")) ?? 0f;
            float b = ParseFloat(ScalarAt(document, name, "b")) ?? 0f;
            float a = ParseFloat(ScalarAt(document, name, "a")) ?? 1f;
            return new Color(r, g, b, a);
        }

        return null;
    }

    private static UnityRef? SafeParseRef(UnityYamlNode? node)
    {
        try { return UnityYaml.ParseRef(node); }
        catch { return null; }
    }

    /// <summary>
    /// Find the path of a texture slot. Modern Unity materials nest them under
    /// m_SavedProperties/m_TexEnvs/&lt;name&gt; with the reference in m_Texture and tiling in
    /// m_Scale/m_Offset; older ones keep the name at the top level with nested scale/offset.
    /// </summary>
    private static string[]? FindTexturePath(UnityDocument document, string[] names)
    {
        foreach (string name in names)
        {
            string[] modern = ["m_SavedProperties", "m_TexEnvs", name];
            if (Get(document, modern) != null) return modern;

            string[] legacy = [name];
            if (Get(document, legacy) != null) return legacy;
        }

        return null;
    }

    private static Float4 ReadScaleOffset(UnityDocument document, string[] texturePath)
    {
        float? sx = ReadFloat(document, [.. texturePath, "m_Scale", "x"])
                    ?? ReadFloat(document, [.. texturePath, "scale", "x"]);
        float? sy = ReadFloat(document, [.. texturePath, "m_Scale", "y"])
                    ?? ReadFloat(document, [.. texturePath, "scale", "y"]);
        float? ox = ReadFloat(document, [.. texturePath, "m_Offset", "x"])
                    ?? ReadFloat(document, [.. texturePath, "offset", "x"]);
        float? oy = ReadFloat(document, [.. texturePath, "m_Offset", "y"])
                    ?? ReadFloat(document, [.. texturePath, "offset", "y"]);

        // Older materials keep tiling in <name>_ST rather than nested in the texture node.
        if (sx == null && sy == null && ox == null && oy == null)
        {
            string st = texturePath[^1] + "_ST";
            string[] floats = ["m_SavedProperties", "m_Floats", st];
            sx = ReadFloat(document, [.. floats, "x"]) ?? ReadFloat(document, st, "x");
            sy = ReadFloat(document, [.. floats, "y"]) ?? ReadFloat(document, st, "y");
            ox = ReadFloat(document, [.. floats, "z"]) ?? ReadFloat(document, st, "z");
            oy = ReadFloat(document, [.. floats, "w"]) ?? ReadFloat(document, st, "w");
        }

        return new Float4(sx ?? 1f, sy ?? 1f, ox ?? 0f, oy ?? 0f);
    }

    private static void ApplyTexture(
        Material material,
        UnityDocument document,
        string[] unityNames,
        string[] targets,
        Func<UnityRef, Texture2D?> resolve)
    {
        if (FindTexturePath(document, unityNames) is not { } texturePath) return;

        // m_Texture holds the reference in the modern layout; the legacy layout uses the node itself.
        UnityYamlNode? node = Get(document, [.. texturePath, "m_Texture"]) ?? Get(document, texturePath);
        if (SafeParseRef(node) is not { IsNull: false } reference) return;

        Texture2D? texture = resolve(reference);
        if (!texture.IsValid()) return;

        Float4 scaleOffset = ReadScaleOffset(document, texturePath);
        foreach (string target in targets)
        {
            material.SetTexture(target, texture);
            material.SetTextureScaleOffset(target, scaleOffset);
        }
    }

    private static bool IsVolumeProfile(UnityDocument document)
    {
        if (document.Fields.ContainsKey("m_Components") || document.Fields.ContainsKey("components"))
            return true;

        string? name = ScalarText(Get(document, "m_Name"));
        return name != null &&
            (name.Contains("VolumeProfile", StringComparison.OrdinalIgnoreCase) ||
             name.Contains("Volume Profile", StringComparison.OrdinalIgnoreCase));
    }
