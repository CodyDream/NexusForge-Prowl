using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace Prowl.Editor.UnityShaders;

/// <summary>
/// Turns the GLSL Slang emits for a <c>glsl_450</c> target into the ShaderDef form Prowl imports.
/// Graphite prepends its own <c>#version 460</c> and assigns all resource bindings, so Slang's
/// version directives, descriptor set/binding layouts and default uniform blocks are dropped in
/// favour of the loose declarations Graphite expects. Varying locations and semantic names survive
/// unchanged, because vertex buffers are bound by those names.
/// </summary>
internal static class SlangGlslRewrite
{
    private static readonly Regex s_layout = new(@"layout\s*\((?<items>[^)]*)\)", RegexOptions.Compiled);
    private const string s_layoutPrefix = @"(?:layout\s*\([^)]*\)\s*)*";
    private static readonly Regex s_block = new(
        @"(?<layouts>" + s_layoutPrefix + @")uniform\s+(?<block>[A-Za-z_]\w*)\s*\{(?<body>[^{}]*)\}\s*(?<instance>[A-Za-z_]\w*)?\s*;",
        RegexOptions.Compiled | RegexOptions.Singleline);
    private static readonly Regex s_uniform = new(
        @"^\s*(?<layouts>" + s_layoutPrefix + @")uniform\s+(?<rest>[^;]+);\s*$",
        RegexOptions.Compiled | RegexOptions.Singleline);
    private static readonly Regex s_qualifierOnly = new(
        @"^\s*layout\s*\([^)]*\)\s*(?:uniform|buffer)\s*;\s*$", RegexOptions.Compiled);
    private static readonly Regex s_localSize = new(
        @"^\s*layout\s*\([^)]*local_size[^)]*\)\s*in\s*;\s*$", RegexOptions.Compiled);
    private static readonly Regex s_member = new(
        @"^(?<type>[A-Za-z_]\w*)\s+(?<name>[A-Za-z_]\w*)(?<array>\s*\[[^\]]*\])?\s*$", RegexOptions.Compiled);
    private static readonly Regex s_matrixType = new(@"^mat[234](x[234])?$", RegexOptions.Compiled);
    private static readonly Regex s_bindingItem = new(@"^(?:binding|set)\s*=|^std(?:140|430)$", RegexOptions.Compiled | RegexOptions.IgnoreCase);

    /// <summary>Builds a graphics shader with one pass per vertex/fragment pair.</summary>
    internal static string BuildGraphics(string name, IReadOnlyList<GraphicsPass> passes)
    {
        var sharedStructs = new OrderedSet();
        var sharedUniforms = new OrderedSet();

        var built = new List<(string Name, StageResult Vertex, StageResult Fragment)>(passes.Count);
        foreach (GraphicsPass pass in passes)
        {
            StageResult vertex = RewriteStage(pass.Vertex);
            StageResult fragment = RewriteStage(pass.Fragment);
            sharedStructs.AddRange(vertex.Structs);
            sharedStructs.AddRange(fragment.Structs);
            sharedUniforms.AddRange(vertex.Uniforms);
            sharedUniforms.AddRange(fragment.Uniforms);
            built.Add((pass.Name, vertex, fragment));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> Compiled from Slang by Prowl's unity_shaders_compile pipeline. Do not edit.");
        sb.AppendLine("Shader \"" + name + "\"");
        sb.AppendLine("{");
        foreach ((string passName, StageResult vertex, StageResult fragment) in built)
        {
            sb.AppendLine("    Pass");
            sb.AppendLine("    {");
            if (passName.Length > 0)
                sb.AppendLine("        Name \"" + Escape(passName) + "\"");
            sb.AppendLine();
            sb.AppendLine("        GLSLPROGRAM");

            Section(sb, "Shared", 8, [
                .. sharedStructs.Items.Select(s => s),
                .. sharedUniforms.Items.Select(s => s),
            ]);
            sb.AppendLine();
            Section(sb, "Vertex", 8, vertex.Items);
            sb.AppendLine();
            Section(sb, "Fragment", 8, fragment.Items);

            sb.AppendLine("        ENDGLSL");
            sb.AppendLine("    }");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Builds a compute shader. Every kernel is emitted as a plain <c>void Name()</c> function and
    /// Prowl's ComputeShader wraps it in its own Compute block with the right local_size layout.
    /// </summary>
    internal static string BuildCompute(
        IReadOnlyList<ComputeKernelSource> kernels,
        out IReadOnlyList<string> warnings)
    {
        var warns = new List<string>();
        var sharedStructs = new OrderedSet();
        var sharedUniforms = new OrderedSet();
        var functions = new OrderedSet();

        foreach (ComputeKernelSource kernel in kernels)
        {
            StageResult stage = RewriteStage(kernel.Glsl);
            sharedStructs.AddRange(stage.Structs);
            sharedUniforms.AddRange(stage.Uniforms);

            bool renamed = false;
            foreach (string item in stage.Items)
            {
                Match main = Regex.Match(item, @"\bvoid\s+main\s*\(");
                string text = main.Success
                    ? item[..main.Index] + "void " + kernel.Name + "(" + item[(main.Index + main.Length)..]
                    : item;
                renamed |= main.Success || Regex.IsMatch(item, @"\bvoid\s+" + Regex.Escape(kernel.Name) + @"\s*\(");
                functions.Add(text);
            }
            if (!renamed)
                warns.Add("Kernel '" + kernel.Name + "' has no main() in Slang's GLSL; the emitted .compute may not declare it.");
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> Compiled from Slang by Prowl's unity_shaders_compile pipeline. Do not edit.");
        foreach (ComputeKernelSource kernel in kernels)
            sb.AppendLine($"#pragma kernel {kernel.Name} {kernel.X} {kernel.Y} {kernel.Z}");
        sb.AppendLine();

        foreach (string item in sharedStructs.Items)
            sb.AppendLine(item);
        if (sharedStructs.Count > 0 && sharedUniforms.Count > 0)
            sb.AppendLine();
        foreach (string item in sharedUniforms.Items)
            sb.AppendLine(item);
        if (functions.Count > 0 && (sharedStructs.Count > 0 || sharedUniforms.Count > 0))
            sb.AppendLine();
        foreach (string item in functions.Items)
            sb.AppendLine(item);

        warnings = warns;
        return sb.ToString();
    }

    private static void Section(StringBuilder sb, string title, int indent, IReadOnlyList<string> items)
    {
        string pad = new(' ', indent);
        sb.AppendLine(pad + title);
        sb.AppendLine(pad + "{");
        foreach (string item in items)
            foreach (string line in item.Replace("\r\n", "\n").Split('\n'))
                sb.AppendLine(line.Length == 0 ? "" : pad + "    " + line);
        sb.AppendLine(pad + "}");
    }

    private static StageResult RewriteStage(string glsl)
    {
        var result = new StageResult();
        // Slang's #line directives point back into the .slang source, while Graphite injects its own
        // #line directives for the generated ShaderDef file. Drop them everywhere, including inside
        // function bodies where the top level splitter cannot see them.
        string normalized = Regex.Replace(
            glsl.Replace("\r\n", "\n"),
            @"^[ \t]*#line[^\n]*(?:\n|$)",
            "",
            RegexOptions.Multiline);

        foreach (string item in Split(normalized))
        {
            string text = item.Trim();
            if (text.Length == 0) continue;

            if (text.StartsWith("#version", StringComparison.Ordinal))
                continue;

            Match block = s_block.Match(text);
            if (block.Success)
            {
                RewriteBlock(block, result);
                continue;
            }

            Match uniform = s_uniform.Match(text);
            if (uniform.Success)
            {
                string layout = StripBindings(uniform.Groups["layouts"].Value);
                string declaration = (layout.Length > 0 ? layout + " " : "") + "uniform " + uniform.Groups["rest"].Value.Trim() + ";";
                result.Uniforms.Add(declaration);
                continue;
            }

            // Slang emits "layout(column_major) uniform;" and "layout(column_major) buffer;" as
            // qualifier-only declarations. Graphite's preprocessor does not need them.
            if (s_qualifierOnly.IsMatch(text)) continue;

            if (s_localSize.IsMatch(text))
                continue;

            if (text.StartsWith("struct ", StringComparison.Ordinal))
            {
                result.Structs.Add(text);
                continue;
            }

            result.Items.Add(text);
        }

        // Slang references uniform blocks through a generated instance, e.g. _S1._Color. Graphite
        // binds loose uniforms by name instead, so those member accesses are rewritten here.
        foreach ((string instance, string member, string replacement) in result.Renames)
        {
            string pattern = @"\b" + Regex.Escape(instance) + @"\s*\.\s*" + Regex.Escape(member) + @"\b";
            for (int i = 0; i < result.Items.Count; i++)
                result.Items[i] = Regex.Replace(result.Items[i], pattern, replacement);
        }

        // The structs Slang generates for uniform blocks are dead once the block is unpacked.
        foreach (string declaration in result.Structs.ToList())
        {
            Match name = Regex.Match(declaration, @"\bstruct\s+([A-Za-z_]\w*)");
            if (!name.Success) continue;
            string word = @"\b" + Regex.Escape(name.Groups[1].Value) + @"\b";
            bool used = result.Items.Any(item => Regex.IsMatch(item, word))
                || result.Uniforms.Any(item => Regex.IsMatch(item, word))
                || result.Structs.Any(item => item != declaration && Regex.IsMatch(item, word));
            if (!used) result.Structs.Remove(declaration);
        }

        return result;
    }

    private static void RewriteBlock(Match block, StageResult result)
    {
        string instance = block.Groups["instance"].Value;
        bool rowMajorBlock = block.Groups["layouts"].Value.Contains("row_major", StringComparison.OrdinalIgnoreCase);

        foreach (string part in block.Groups["body"].Value.Split(';'))
        {
            if (string.IsNullOrWhiteSpace(part)) continue;

            bool rowMajor = rowMajorBlock || part.Contains("row_major", StringComparison.OrdinalIgnoreCase);
            string clean = Regex.Replace(part, @"layout\s*\([^)]*\)", "");
            clean = Regex.Replace(clean, @"\b(?:row_major|column_major|flat|smooth|noperspective)\b", "").Trim();

            Match member = s_member.Match(clean);
            if (!member.Success)
            {
                // Keep the declaration verbatim rather than dropping a global Slang emitted.
                result.Uniforms.Add("uniform " + clean + ";");
                continue;
            }

            string type = NormalizeMatrix(member.Groups["type"].Value);
            string name = member.Groups["name"].Value;
            string array = member.Groups["array"].Value;
            result.Uniforms.Add($"uniform {type} {name}{array};");

            if (instance.Length > 0)
            {
                string value = rowMajor && s_matrixType.IsMatch(type) ? $"transpose({name})" : name;
                result.Renames.Add((instance, name, value));
            }
        }
    }

    private static string StripBindings(string layouts)
    {
        if (string.IsNullOrWhiteSpace(layouts)) return "";

        var kept = new List<string>();
        foreach (Match match in s_layout.Matches(layouts))
        {
            foreach (string item in match.Groups["items"].Value.Split(','))
            {
                string trimmed = item.Trim();
                if (trimmed.Length > 0 && !s_bindingItem.IsMatch(trimmed))
                    kept.Add(trimmed);
            }
        }
        return kept.Count == 0 ? "" : "layout(" + string.Join(", ", kept) + ")";
    }

    private static string NormalizeMatrix(string type) => type switch
    {
        "mat4x4" => "mat4",
        "mat3x3" => "mat3",
        "mat2x2" => "mat2",
        _ => type,
    };

    private static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");

    /// <summary>Splits target GLSL into directives and top level declarations.</summary>
    private static List<string> Split(string glsl)
    {
        var items = new List<string>();
        int i = 0;
        while (i < glsl.Length)
        {
            while (i < glsl.Length && char.IsWhiteSpace(glsl[i])) i++;
            if (i >= glsl.Length) break;

            int start = i;
            if (glsl[i] == '#')
            {
                while (i < glsl.Length && glsl[i] != '\n') i++;
                items.Add(glsl[start..i].TrimEnd());
                continue;
            }

            int parens = 0, braces = 0;
            bool function = false;
            for (; i < glsl.Length; i++)
            {
                char c = glsl[i];
                if (c is '(' or '[') parens++;
                else if (c is ')' or ']') parens--;
                else if (c == '{')
                {
                    if (braces == 0 && parens == 0)
                        function = glsl[start..i].TrimEnd().EndsWith(')');
                    braces++;
                }
                else if (c == '}' && --braces == 0 && parens == 0 && function)
                    break;
                else if (c == ';' && braces == 0 && parens == 0)
                    break;
            }

            if (i >= glsl.Length)
            {
                items.Add(glsl[start..]);
                break;
            }

            items.Add(glsl[start..(i + 1)]);
            i++;
        }
        return items;
    }

    private sealed class StageResult
    {
        public readonly List<string> Items = new();
        public readonly List<string> Uniforms = new();
        public readonly List<string> Structs = new();
        public readonly List<(string Instance, string Member, string Replacement)> Renames = new();
    }

    private sealed class OrderedSet
    {
        private readonly HashSet<string> _seen = new(StringComparer.Ordinal);
        public readonly List<string> Items = new();
        public int Count => Items.Count;

        public void Add(string item)
        {
            // Whitespace between tokens is not meaningful for declarations, so collapse it before
            // deciding whether two stages emitted the same thing.
            string key = Regex.Replace(item.Trim(), @"\s+", " ");
            if (_seen.Add(key)) Items.Add(item.Trim());
        }

        public void AddRange(IEnumerable<string> items)
        {
            foreach (string item in items) Add(item);
        }
    }
}

internal sealed record GraphicsPass(string Name, string Vertex, string Fragment);

internal sealed record ComputeKernelSource(string Name, int X, int Y, int Z, string Glsl);
